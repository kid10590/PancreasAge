#!/bin/bash
# ============================================================
# 3_2_run_gwas_regenie.sh — REGENIE two-step GWAS (dual mode, for cross-validation)
#
# Reference: cardiovascular_ageing/genetic analysis/regenie/regenie.md
# QC (performed by plink2; REGENIE itself has no QC filtering):
#   --mac 100 --maf 0.01 --hwe 1e-15 keep-fewhet --geno 0.1 --mind 0.1
# Step 1: chr1 polygenic effect modeling (approximate, see note below)
# Step 2: conditional association across 22 chromosomes (tests only HQ SNPs passing QC)
#
# Usage (two equivalent forms):
#   bash code/03_genetics/3_2_run_gwas_regenie.sh --mode full        (or --full)
#   bash code/03_genetics/3_2_run_gwas_regenie.sh --mode discovery   (or --discovery / --prs)
#
# Output:
#   full      → <RES_ROOT>/gwas_regenie_results/    (full sample, aligned with gwas_plink_results)
#   discovery → <RES_ROOT>/gwas_regenie_discovery/  (aligned with gwas_plink_discovery)
#
# ⚠️ Note: Step 1 fits the polygenic effect using chr1 only. The reference workflow uses merged
#    c1-22 bfile, but this data's pgen is split by chromosome (chr1 alone ~208GB), so merging
#    is impractical. This is an approximation: when testing chr1 the LOCO prediction is empty, and when testing other chromosomes the
#    prediction comes only from chr1. Sufficient for cross-validation against plink2, but not a full null model.
# ============================================================
# ── paths (override via env: PANCREASAGE_DATA / PANCREASAGE_OUT / PLINK2 / REGENIE) ──
PKG_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DATA_ROOT="${PANCREASAGE_DATA:-${PKG_ROOT}/data}"
OUT_ROOT="${PANCREASAGE_OUT:-${PKG_ROOT}/results}"
set -e

PLINK2="${PLINK2:-plink2}"
REGENIE="${REGENIE:-regenie}"

if [[ "$PLINK2" == */* ]]; then
    [ -x "$PLINK2" ] || { echo "Error: plink2 not found: $PLINK2"; exit 1; }
elif ! command -v "$PLINK2" >/dev/null 2>&1; then
    echo "Error: plink2 not found in PATH (use \$PLINK2 to specify a full path)"; exit 1
fi
if [[ "$REGENIE" == */* ]]; then
    [ -x "$REGENIE" ] || { echo "Error: regenie not found: $REGENIE"; exit 1; }
elif ! command -v "$REGENIE" >/dev/null 2>&1; then
    echo "Error: regenie not found in PATH (use \$REGENIE to specify a full path)"; exit 1
fi

# ---- mode parsing (accepts --mode full / --full / full / --mode discovery / --discovery) ----
MODE="full"
for ARG in "$@"; do
    case "$ARG" in
        --mode) ;;
        full|--full) MODE="full" ;;
        discovery|--discovery|prs|--prs) MODE="discovery" ;;
    esac
done
if [ "$MODE" != "full" ] && [ "$MODE" != "discovery" ]; then
    echo "Error: unknown mode '$MODE' (options: full / discovery)"
    exit 1
fi

PGEN_DIR="${PGEN_DIR:-${DATA_ROOT}/genotypes/pgen}"
RES_ROOT="${RES_ROOT:-${OUT_ROOT}}"
PHENO_FILE="$RES_ROOT/gwas_inputs/phenotypes.txt"
COVAR_FILE="$RES_ROOT/gwas_inputs/covariates.cov"
# discovery samples after the 7:3 split (generated by 3_1, two columns FID IID)
DISCOVERY_KEEP="$RES_ROOT/prs_analysis/keep_discovery.id"

if [ "$MODE" == "full" ]; then
    OUT_DIR="$RES_ROOT/gwas_regenie_results"
    KEEP_FILE=""   # all samples
    echo "Full-sample REGENIE GWAS (full sample, aligned with gwas_plink_results)"
else
    OUT_DIR="$RES_ROOT/gwas_regenie_discovery"
    KEEP_FILE="$DISCOVERY_KEEP"
    echo "Discovery-only REGENIE GWAS (n=$(wc -l < $DISCOVERY_KEEP), aligned with gwas_plink_discovery)"
fi

mkdir -p "$OUT_DIR"

PHENO_NAME="catb_delta_with_t1_bc_cole"
COVAR_LIST="Sex,Age,Age2,Array,PC1,PC2,PC3,PC4,PC5,PC6,PC7,PC8,PC9,PC10"
THREADS=16

# ═══════════════════════════════════════
# 1. QC: extract HQ common SNPs (only needs to run once)
# ═══════════════════════════════════════
# Reference: MAC>100, MAF>1%, HWE>1e-15, missing<10% (samples & sites)
# At N=22k, MAC=100 corresponds to MAF≈0.5%, appropriate
# HWE=1e-15 only removes extreme aneuploidy-level deviations and will not kill true signal
SNPLIST="$OUT_DIR/hq_common_snps.snplist"
SAMPLELIST="$OUT_DIR/hq_samples.id"

KEEP_ARGS=""
if [ -n "$KEEP_FILE" ]; then
    KEEP_ARGS="--keep $KEEP_FILE"
fi

if [ ! -f "$SNPLIST" ] || [ ! -f "$SAMPLELIST" ]; then
    echo "========================================="
    echo " Step 1/3: QC — extract HQ common SNPs"
    echo "========================================="

    # Run QC on chr1 (largest chromosome, most complete SNP set) and extract the list of passing samples
    $PLINK2 \
        --rm-dup exclude-all \
        --pfile "${PGEN_DIR}/ukb22828_c1_b0_v3" \
        $KEEP_ARGS \
        --mac 100 --maf 0.01 --hwe 1e-15 keep-fewhet --geno 0.1 --mind 0.1 \
        --write-samples --no-id-header \
        --out "${OUT_DIR}/hq_samples" \
        --threads $THREADS

    # Using the list of QC-passing samples, extract passing SNPs chromosome by chromosome
    > "$SNPLIST"  # clear
    for CHR in {1..22}; do
        echo "  chr${CHR}..."
        $PLINK2 \
            --rm-dup exclude-all \
            --pfile "${PGEN_DIR}/ukb22828_c${CHR}_b0_v3" \
            --keep "${SAMPLELIST}" \
            --mac 100 --maf 0.01 --hwe 1e-15 keep-fewhet --geno 0.1 \
            --write-snplist --no-id-header \
            --out "${OUT_DIR}/hq_snps_chr${CHR}" \
            --threads $THREADS
        cat "${OUT_DIR}/hq_snps_chr${CHR}.snplist" >> "$SNPLIST" 2>/dev/null || true
    done
    sort -u "$SNPLIST" -o "$SNPLIST"
    echo "  HQ SNPs: $(wc -l < $SNPLIST)"
    echo "  HQ samples: $(wc -l < $SAMPLELIST)"
else
    echo "[skip] QC already complete ($SNPLIST, $SAMPLELIST)"
fi

# ═══════════════════════════════════════
# 2. REGENIE Step 1: polygenic effect modeling
# ═══════════════════════════════════════
STEP1_OUT="$OUT_DIR/regenie_step1_agedelta"

if [ ! -f "${STEP1_OUT}_pred.list" ]; then
    echo ""
    echo "========================================="
    echo " Step 2/3: REGENIE Step 1 — chr1 polygenic modeling"
    echo "========================================="
    $REGENIE \
        --step 1 \
        --pgen "${PGEN_DIR}/ukb22828_c1_b0_v3" \
        --phenoFile "$PHENO_FILE" \
        --covarFile "$COVAR_FILE" \
        --phenoCol "$PHENO_NAME" \
        --covarColList "$COVAR_LIST" \
        --extract "$SNPLIST" \
        --keep "$SAMPLELIST" \
        --bsize 1000 \
        --lowmem --lowmem-prefix "${OUT_DIR}/regenie_lowmem" \
        --threads $THREADS \
        --gz \
        --out "$STEP1_OUT"
    echo "  Step 1 complete → ${STEP1_OUT}_pred.list"
else
    echo "[skip] Step 1 already complete"
fi

# ═══════════════════════════════════════
# 3. REGENIE Step 2: conditional GWAS
# ═══════════════════════════════════════
echo ""
echo "========================================="
echo " Step 3/3: REGENIE Step 2 — conditional GWAS across 22 chromosomes"
echo "========================================="

for CHR in {1..22}; do
    CHR_OUT="${OUT_DIR}/gwas_chr${CHR}"
    CHR_SNPLIST="${OUT_DIR}/hq_snps_chr${CHR}.snplist"
    if [ -f "${CHR_OUT}_${PHENO_NAME}.regenie" ] || [ -f "${CHR_OUT}_${PHENO_NAME}.regenie.gz" ]; then
        echo "  chr${CHR}: results already exist → skipping"
        continue
    fi
    echo "  chr${CHR}..."
    $REGENIE \
        --step 2 \
        --pred "${STEP1_OUT}_pred.list" \
        --pgen "${PGEN_DIR}/ukb22828_c${CHR}_b0_v3" \
        --phenoFile "$PHENO_FILE" \
        --covarFile "$COVAR_FILE" \
        --phenoCol "$PHENO_NAME" \
        --covarColList "$COVAR_LIST" \
        --extract "$CHR_SNPLIST" \
        --keep "$SAMPLELIST" \
        --bsize 400 \
        --threads $THREADS \
        --gz \
        --out "$CHR_OUT"
done

echo ""
echo "========================================="
echo " REGENIE GWAS complete! Mode: $MODE"
echo " Result directory: $OUT_DIR"
echo " Step 1 prediction: ${STEP1_OUT}_pred.list"
echo " Step 2 results: ${OUT_DIR}/gwas_chr*_${PHENO_NAME}.regenie.gz"
echo "========================================="
