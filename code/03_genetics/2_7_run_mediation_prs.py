def main():
    global PRS_DIR, PRS_CSV, LEAD_FILE, KEEP_FILE_PRS, T2D_DIR, OUT_DIR, PHENO_COVAR_CSV
    parser = argparse.ArgumentParser()
    parser.add_argument("--prs-dir", type=str, default=DEFAULT_PRS_DIR,
                        help="APAG PRS directory, default prs_analysis")
    parser.add_argument("--prs-csv", type=str, default=None,
                        help="APAG PRS csv, default <prs-dir>/APAG_PRS_raw.csv")
    parser.add_argument("--lead-file", type=str, default=None,
                        help="lead SNP table, default <prs-dir>/prs_build/lead_full.csv")
    parser.add_argument("--t2d-dir", type=str, default=None,
                        help="T2D PRS directory, default same as --prs-dir")
    parser.add_argument("--out-dir", type=str, default=None,
                        help="Output directory, default <Disease_Phenotype_Analysis>/Mediation_PRS")
    parser.add_argument("--pheno-covar", type=str, default=None,
                        help="Covariate table, default gwas_inputs/phenotype_covariates_merged.csv")
    args = parser.parse_args()

    PRS_DIR = args.prs_dir
    PRS_CSV = args.prs_csv or os.path.join(PRS_DIR, "APAG_PRS_raw.csv")
    LEAD_FILE = args.lead_file or os.path.join(PRS_DIR, "prs_build", "lead_full.csv")
    KEEP_FILE_PRS = os.path.join(PRS_DIR, "keep_all.id")
    T2D_DIR = args.t2d_dir or PRS_DIR
    OUT_DIR = args.out_dir or os.path.join(ANALYSIS_ROOT, "Mediation_PRS")
    if args.pheno_covar:
        PHENO_COVAR_CSV = args.pheno_covar

    print("=" * 60)
    print("  PRS mediation analysis: APAG_PRS → APAG → diabetes")
    print("=" * 60)
    print(f"  PRS: {PRS_CSV}")
    print(f"  lead: {LEAD_FILE}")
    setup_output_dir()

    prs_df, clumped_ids, ctrb_ids, snp_info, _ = load_prs_and_clumped_snps()

    keep_file = os.path.join(OUT_DIR, "_keep_fid_iid.txt")
    # The new keep_all.id is already in two-column FID IID format; reuse directly
    if os.path.exists(KEEP_FILE_PRS):
        keep_file = KEEP_FILE_PRS
    else:
        orig_keep = os.path.join(INPUT_DIR, "keep_test_ukb_test_ill.id")
        if not os.path.exists(keep_file):
            subprocess.run(f"awk '{{print $1, $1}}' {orig_keep} > {keep_file}", shell=True, check=True)

    prs_df = subtract_ctrb_prs(prs_df, ctrb_ids, snp_info, keep_file)
    df, pc_cols = merge_prs_mediation_data(prs_df)

    res_full = prs_mediation(df, 'prs_score', pc_cols, "PRS_total (genome-wide clumped SNPs)")
    res_noCTRB = prs_mediation(df, 'prs_noCTRB', pc_cols, "PRS_noCTRB (excluding the CTRB1/2 region)")
    res_t2d = sensitivity_t2d(df, pc_cols, 'prs_score')

    # Write summary
    summary_path = os.path.join(OUT_DIR, "prs_mediation_results.txt")
    with open(summary_path, "w") as f:
        f.write(f"PRS mediation analysis\n")
        f.write(f"PRS source: {args.prs_csv}\n")
        f.write(f"Clumped SNPs: {len(clumped_ids)}, within CTRB1/2: {len(ctrb_ids)}\n")
        f.write(f"Samples: {len(df)} (case={df['is_case'].sum()}, ctrl={(df['is_case']==0).sum()})\n\n")
        for r in [res_full, res_noCTRB]:
            f.write(f"--- {r['label']} ---\n")
            f.write(f"a={r['a']:.4f} P={r['a_p']:.2e} | b={r['b']:.4f} OR={r['b_or']:.4f} P={r['b_p']:.2e}\n")
            f.write(f"c={r['c']:.4f} OR={r['c_or']:.4f} P={r['c_p']:.2e} | c'={r['cp']:.4f} P={r['cp_p']:.2e}\n")
            f.write(f"ab={r['ab']:.4f} Sobel P={r['sobel_p']:.2e} | Bootstrap 95%CI [{r['ab_ci'][0]:.4f},{r['ab_ci'][1]:.4f}]\n")
            f.write(f"Classification: {r['med_type']}\n\n")
        if res_t2d:
            f.write(f"--- T2D control ---\n")
            f.write(f"APAG PRS (+T2D): OR={res_t2d['apag_or_given_t2d']:.4f} P={res_t2d['apag_p_given_t2d']:.2e}\n")

    print(f"\n  → {summary_path}")
    print("\nDone!")


if __name__ == "__main__":
    main()
