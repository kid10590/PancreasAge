# CTRB1/2 region (consistent with 4_0_run_prs.sh: rs72802342 chr16:75234872 ±500kb)
CTRB_REGION = {"chr": 16, "start": 74_734_872, "end": 75_734_872}


def setup_output_dir():
    os.makedirs(OUT_DIR, exist_ok=True)
    print(f"Output directory: {OUT_DIR}")


# ═══════════════════════════════════════
# Step 1: Load PRS + build PRS_noCTRB
# ═══════════════════════════════════════

def load_prs_and_clumped_snps():
    print("\n" + "=" * 60)
    print(" Step 1: Load PRS data")
    print("=" * 60)

    prs = pd.read_csv(PRS_CSV)
    prs['IID'] = prs['IID'].astype(str)

    # Auto-select PRS column
    if 'PRS_std' in prs.columns:
        prs['prs_score'] = prs['PRS_std']
        used = 'PRS_std'
    elif 'PRS' in prs.columns:
        prs['prs_score'] = (prs['PRS'] - prs['PRS'].mean()) / prs['PRS'].std()
        used = 'PRS'
    else:
        cols = [c for c in prs.columns if c not in ('FID', 'IID')]
        prs['prs_score'] = (prs[cols[0]] - prs[cols[0]].mean()) / prs[cols[0]].std()
        used = cols[0]
    print(f"  PRS column: {used}, samples: {len(prs)}, mean={prs['prs_score'].mean():.3f}")

    # lead SNP list (with position+beta, from lead_full.csv generated by 4_0_run_prs.sh)
    lead = pd.read_csv(LEAD_FILE)
    lead.columns = [c.strip().upper() for c in lead.columns]
    cmap = {}
    for c in lead.columns:
        if c in ('CHROM', 'CHR'): cmap[c] = 'CHROM'
        elif c in ('POS', 'BP'): cmap[c] = 'POS'
    lead = lead.rename(columns=cmap)
    if 'BETA' not in lead.columns:
        lead = lead.rename(columns={c: 'BETA' for c in lead.columns if c in ('BETA', 'BETA1', 'B')})
    clumped_ids = set(lead['ID'].astype(str))
    print(f"  Lead SNPs (clumped): {len(clumped_ids)}")

    # Find lead SNPs within the CTRB1/2 region
    lead_chr = pd.to_numeric(lead['CHROM'], errors='coerce')
    lead_pos = pd.to_numeric(lead['POS'], errors='coerce')
    ctrb_ids = lead[(lead_chr == CTRB_REGION['chr']) &
                    (lead_pos >= CTRB_REGION['start']) &
                    (lead_pos <= CTRB_REGION['end'])]['ID'].astype(str).tolist()
    print(f"  Lead SNPs within the CTRB1/2 region: {len(ctrb_ids)}")

    return prs, clumped_ids, ctrb_ids, lead, used


def subtract_ctrb_prs(prs_df, ctrb_ids, snp_info, keep_file):
    """PRS_noCTRB = PRS_total - CTRB1/2_SNP_contributions"""
    print("\n" + "-" * 40)
    print(" Building PRS_noCTRB (excluding the CTRB1/2 region)")
    print("-" * 40)

    if len(ctrb_ids) == 0:
        prs_df['prs_noCTRB'] = prs_df['prs_score']
        return prs_df

    a1_col = 'A1' if 'A1' in snp_info.columns else 'ALLELE1'
    allele_map = dict(zip(snp_info['ID'].astype(str),
                          snp_info[a1_col].astype(str))) if a1_col in snp_info.columns else None
    ctrb_geno = _extract_snps_batch(ctrb_ids, CTRB_REGION['chr'], keep_file, "ctrb_prs",
                                    allele_map=allele_map)
    if ctrb_geno is None:
        prs_df['prs_noCTRB'] = prs_df['prs_score']
        return prs_df

    ctrb_geno['IID'] = ctrb_geno['IID'].astype(str)
    prs_df = prs_df.merge(ctrb_geno, on='IID', how='left')

    beta_map = dict(zip(snp_info['ID'], snp_info['BETA']))
    ctrb_contrib = pd.Series(0.0, index=prs_df.index)
    for sid in ctrb_ids:
        if sid in prs_df.columns and sid in beta_map:
            ctrb_contrib += prs_df[sid].fillna(0) * beta_map[sid]

    prs_df['prs_noCTRB'] = prs_df['prs_score'] - ctrb_contrib
    print(f"  PRS_total mean={prs_df['prs_score'].mean():.4f}, "
          f"PRS_noCTRB mean={prs_df['prs_noCTRB'].mean():.4f}")
    return prs_df


def _extract_snps_batch(snp_ids, chr_num, keep_file, batch_name, allele_map=None):
    out_prefix = os.path.join(OUT_DIR, f"snp_batch_{batch_name}")
    raw_file = f"{out_prefix}.raw"
    if os.path.exists(raw_file):
        return _load_raw(raw_file, allele_map)

    snp_list_file = os.path.join(OUT_DIR, f"_extract_{batch_name}.txt")
    with open(snp_list_file, 'w') as f:
        for sid in snp_ids: f.write(f"{sid}\n")

    pgen = os.path.join(PGEN_DIR, f"ukb22828_c{chr_num}_b0_v3")
    keep_arg = ["--keep", keep_file] if keep_file and os.path.exists(keep_file) else []
    cmd = [PLINK2, "--pfile", pgen, "--extract", snp_list_file,
           "--export", "A", "--out", out_prefix, "--threads", "4", "--memory", "8000"] + keep_arg
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(raw_file):
        print(f"  [WARNING] extraction failed: {r.stderr[-200:]}")
        return None
    return _load_raw(raw_file, allele_map)


def _load_raw(raw_file, allele_map=None):
    df = pd.read_csv(raw_file, sep=r'\s+')
    snp_cols = [c for c in df.columns if c not in ('FID', 'IID', 'PAT', 'MAT', 'SEX', 'PHENOTYPE')]
    dosage_cols = [c for c in snp_cols if not c.endswith('_HET')]
    result = df[['IID']].copy(); result['IID'] = result['IID'].astype(str)
    for col in dosage_cols:
        # --export A column name: SNPID_allele (counted allele is the last segment)
        if '_' in col:
            counted_allele = col.rsplit('_', 1)[1].upper()
            snp_name = col.rsplit('_', 1)[0]
        else:
            counted_allele, snp_name = None, col
        dos = pd.to_numeric(df[col], errors='coerce')
        if allele_map and counted_allele and snp_name in allele_map:
            eff = str(allele_map[snp_name]).upper()
            if eff and counted_allele != eff:
                dos = 2.0 - dos
                print(f"  [flip] {snp_name}: counted allele {counted_allele} -> effect allele {eff}")
        result[snp_name] = dos
    return result


# ═══════════════════════════════════════
# Step 2: Merge data
# ═══════════════════════════════════════

def merge_prs_mediation_data(prs_df):
    print("\n" + "=" * 60)
    print(" Step 2: Merge PRS mediation analysis data")
    print("=" * 60)

    matched = pd.read_csv(MATCHED_CSV, low_memory=False)
    matched['eid'] = matched['eid'].astype(str)
    covar = pd.read_csv(PHENO_COVAR_CSV, low_memory=False)
    covar['eid'] = covar['eid'].astype(str)
    pc_cols = [f'PC{i}' for i in range(1, 11)]
    pc_cols = [c for c in pc_cols if c in covar.columns]

    cols = ['eid', 'delta', 'is_case', 'age_use', 'sex_code']
    if 'age_use' not in matched.columns and 'age_gt' in matched.columns:
        matched['age_use'] = matched['age_gt']
    df = matched[cols].copy()

    df = df.merge(prs_df[['IID', 'prs_score', 'prs_noCTRB']],
                  left_on='eid', right_on='IID', how='inner')
    df = df.merge(covar[['eid'] + pc_cols], on='eid', how='left')

    age_mean = df['age_use'].mean()
    df['age_c'] = df['age_use'] - age_mean
    df['age_c_sq'] = df['age_c'] ** 2

    for col in ['prs_score', 'prs_noCTRB']:
        if col in df.columns:
            df[col] = (df[col] - df[col].mean()) / df[col].std()

    required = ['delta', 'is_case', 'prs_score', 'age_c', 'age_c_sq', 'sex_code']
    df = df.dropna(subset=required).copy()
    for pc in pc_cols:
        if pc in df.columns: df[pc] = df[pc].fillna(0)

    print(f"  Analysis samples: {len(df)} (case={df['is_case'].sum()}, ctrl={(df['is_case']==0).sum()})")
    df.to_csv(os.path.join(OUT_DIR, "merged_prs_mediation_data.csv"), index=False)
    return df, pc_cols


# ═══════════════════════════════════════
# Step 3: PRS mediation
# ═══════════════════════════════════════

def prs_mediation(df, prs_col, pc_cols, label=""):
    print(f"\n{'='*60}")
    print(f" {label}")
    print(f"{'='*60}")

    covar_list = ['age_c', 'age_c_sq', 'sex_code'] + [c for c in pc_cols if c in df.columns]
    covar_str = ' + '.join(covar_list)

    ma = sm.OLS.from_formula(f"delta ~ {prs_col} + {covar_str}", data=df).fit()
    mc = sm.Logit.from_formula(f"is_case ~ {prs_col} + {covar_str}", data=df).fit(disp=0)
    mcp = sm.Logit.from_formula(f"is_case ~ {prs_col} + delta + {covar_str}", data=df).fit(disp=0)

    a = ma.params[prs_col]; a_se = ma.bse[prs_col]; a_p = ma.pvalues[prs_col]
    b = mcp.params['delta']; b_se = mcp.bse['delta']; b_p = mcp.pvalues['delta']
    c = mc.params[prs_col]; c_se = mc.bse[prs_col]; c_p = mc.pvalues[prs_col]
    cp = mcp.params[prs_col]; cp_se = mcp.bse[prs_col]; cp_p = mcp.pvalues[prs_col]
    ab = a * b
    sobel_se = np.sqrt(a**2 * b_se**2 + b**2 * a_se**2)
    sobel_z = ab / sobel_se if sobel_se > 0 else 0
    sobel_p = 2 * (1 - stats.norm.cdf(abs(sobel_z)))
    prop = ab / c if abs(c) > 1e-10 else np.nan

    print(f"  a (PRS→APAG):    {a:.4f}  P={a_p:.2e}")
    print(f"  b (APAG→DM):     {b:.4f}  P={b_p:.2e}  OR={np.exp(b):.4f}")
    print(f"  c (PRS→DM,total):   {c:.4f}  P={c_p:.2e}  OR={np.exp(c):.4f}")
    print(f"  c'(PRS→DM,direct): {cp:.4f}  P={cp_p:.2e}  OR={np.exp(cp):.4f}")
    print(f"  ab:              {ab:.4f}  Sobel Z={sobel_z:.2f}  P={sobel_p:.2e}")

    # Bootstrap
    np.random.seed(42)
    n = len(df)
    ab_boot, cp_boot = [], []
    for _ in range(5000):
        idx = np.random.choice(n, size=n, replace=True)
        bdf = df.iloc[idx]
        try:
            ba = sm.OLS.from_formula(f"delta ~ {prs_col} + {covar_str}", data=bdf).fit().params[prs_col]
            bm = sm.Logit.from_formula(f"is_case ~ {prs_col} + delta + {covar_str}", data=bdf).fit(disp=0)
            ab_boot.append(ba * bm.params['delta'])
            cp_boot.append(bm.params[prs_col])
        except Exception:
            continue

    ab_ci = np.percentile(ab_boot, [2.5, 97.5])
    cp_ci = np.percentile(cp_boot, [2.5, 97.5])
    ab_sig = not (ab_ci[0] <= 0 <= ab_ci[1])
    cp_sig = not (cp_ci[0] <= 0 <= cp_ci[1])

    if not ab_sig: med_type = "No mediation effect"
    elif cp_sig: med_type = "Partial mediation"
    else: med_type = "Full mediation"

    print(f"  Bootstrap ab 95%CI: [{ab_ci[0]:.4f}, {ab_ci[1]:.4f}] → {'✓' if ab_sig else '✗'}")
    print(f"  Bootstrap c' 95%CI: [{cp_ci[0]:.4f}, {cp_ci[1]:.4f}]")
    print(f"  Classification: {med_type}")

    return {'label': label, 'a': a, 'a_p': a_p, 'b': b, 'b_p': b_p, 'b_or': np.exp(b),
            'c': c, 'c_p': c_p, 'c_or': np.exp(c), 'cp': cp, 'cp_p': cp_p, 'cp_or': np.exp(cp),
            'ab': ab, 'sobel_z': sobel_z, 'sobel_p': sobel_p, 'prop': prop,
            'ab_ci': ab_ci, 'cp_ci': cp_ci, 'med_type': med_type, 'ab_sig': ab_sig}


# ═══════════════════════════════════════
# Sensitivity: T2D control
# ═══════════════════════════════════════

def sensitivity_t2d(df, pc_cols, prs_col):
    print(f"\n{'='*60}")
    print(" Sensitivity: controlling for T2D PRS")
    print(f"{'='*60}")

    # Fix: use the known T2D PRS output by 4_4 (DIAMANTE ieu-a-23) instead of a nonexistent file
    t2d_file = os.path.join(T2D_DIR, "T2D_PRS_ieu-a-23_raw.csv")
    if not os.path.exists(t2d_file):
        print(f"  T2D PRS file does not exist: {t2d_file}, skipping")
        return None

    t2d = pd.read_csv(t2d_file); t2d['IID'] = t2d['IID'].astype(str)
    if 't2d_prs' not in t2d.columns:
        cols = [c for c in t2d.columns if c not in ('FID', 'IID')]
        t2d['t2d_prs'] = t2d[cols[0]]

    df2 = df.merge(t2d[['IID', 't2d_prs']], left_on='eid', right_on='IID', how='inner')
    df2['t2d_prs'] = (df2['t2d_prs'] - df2['t2d_prs'].mean()) / df2['t2d_prs'].std()

    covar_list = ['age_c', 'age_c_sq', 'sex_code', 't2d_prs'] + [c for c in pc_cols if c in df2.columns]
    covar_str = ' + '.join(covar_list)

    m_full = sm.Logit.from_formula(f"is_case ~ t2d_prs + {prs_col} + {covar_str}", data=df2).fit(disp=0)
    apag_or = np.exp(m_full.params[prs_col]); apag_p = m_full.pvalues[prs_col]
    print(f"  APAG PRS (+T2D control): OR={apag_or:.4f}, P={apag_p:.2e}")
    return {'apag_or_given_t2d': apag_or, 'apag_p_given_t2d': apag_p, 'independent': apag_p < 0.05}


