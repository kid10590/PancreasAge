#!/usr/bin/env python
"""
2_7_run_mediation_prs.py — PRS mediation analysis: APAG_PRS → APAG → diabetes

Performs mediation analysis using the PRS of genome-wide clumped SNPs as the instrumental variable.
Complements 2_6 (single SNP): 2_6 focuses on the CTRB1/2 locus mechanism, 2_7 does genome-wide polygenic causal inference.

Sensitivity:
  - Does mediation hold after excluding the CTRB1/2 region from the PRS?
  - Does APAG PRS still contribute independently after controlling for known T2D PRS?

Usage:
  python code/03_genetics/2_7_run_mediation_prs.py
  python code/03_genetics/2_7_run_mediation_prs.py --prs-csv /path/to/APAG_PRS_raw.csv
"""
