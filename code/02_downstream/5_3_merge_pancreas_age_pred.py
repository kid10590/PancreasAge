#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
5_3 Append pancreatic age model prediction columns to cohort tables

Source: Results/swin3d_kl_reg_0801/infer_cv/master_ukb_predictions.csv
  - healthy (is_healthy=1):  5-fold OOF predictions (age_pred_raw / age_pred_bc)
  - unhealthy (is_healthy=0): 5-fold average predictions (age_pred_raw / age_pred_bc)

New columns:
  age_pred_raw  pancreatic age output by the model (raw)
  age_pred_bc   pancreatic age after bias correction (bias-corrected)

Input/output: ukb_{healthy,ill}_cohort.csv under cohort_tables/
  (if cohort_tables/ was generated by another user and is not writable, output to cohort_tables_pred/)
"""
import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common"))
from paths import OUT_ROOT, INFER_DIR  # noqa: E402

DEFAULT_OUT = os.path.join(OUT_ROOT, "cohort_tables_pred")
DEFAULT_MASTER = os.path.join(INFER_DIR, "master_ukb_predictions.csv")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--master", default=DEFAULT_MASTER)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--src", default=os.path.join(OUT_ROOT, "cohort_tables"))
    args = ap.parse_args()

    master = pd.read_csv(args.master, usecols=["eid", "age_pred_raw", "age_pred_bc"])
    master["eid"] = master["eid"].astype(str)
    master = master.drop_duplicates(subset="eid")

    os.makedirs(args.out, exist_ok=True)

    for name, n_expected in [("healthy", 40649), ("ill", 14477)]:
        path = os.path.join(args.src, f"ukb_{name}_cohort.csv")
        df = pd.read_csv(path, dtype={"eid": str})
        before = df.shape[1]
        df = df.merge(master, on="eid", how="left")
        missing = df["age_pred_raw"].isna().sum()
        out_path = os.path.join(args.out, f"ukb_{name}_cohort.csv")
        df.to_csv(out_path, index=False)
        print(f"{out_path}: {len(df)} rows, cols {before}->{df.shape[1]}, "
              f"missing pred={missing} (expected n={n_expected})")

    # Quick sample sanity check
    chk = pd.read_csv(os.path.join(args.out, "ukb_healthy_cohort.csv"), dtype={"eid": str}, nrows=3)
    print(chk[["eid", "age", "age_pred_raw", "age_pred_bc"]].to_string(index=False))


if __name__ == "__main__":
    main()